CREATE TABLE media_selection_jobs (
 id VARCHAR(36) NOT NULL,
 user_id BIGINT NOT NULL,
 media_id BIGINT NOT NULL,
 transcript_id BIGINT NOT NULL,
 transcript_revision INT NOT NULL,
 goal VARCHAR(500) NOT NULL,
 state VARCHAR(32) NOT NULL,
 snapshot_json JSON NOT NULL,
 result_json JSON NULL,
 model VARCHAR(255) NOT NULL,
 prompt_version VARCHAR(64) NOT NULL,
 duration_ms BIGINT NOT NULL DEFAULT 0,
 completed_batches INT NOT NULL DEFAULT 0,
 total_batches INT NOT NULL,
 error_code VARCHAR(128) NULL,
 error_message VARCHAR(1000) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 PRIMARY KEY(id),
 KEY idx_selection_owner_media (user_id,media_id,transcript_id,created_at),
 KEY idx_selection_state (state,updated_at),
 CONSTRAINT chk_selection_state CHECK (state IN ('QUEUED','PROCESSING','COMPLETED','FAILED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
